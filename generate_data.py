def gen_price(base):
    """生成模拟价格（带涨跌幅）"""
    change_pct = random.uniform(-9.5, 9.5)
    price = round(base * (1 + change_pct / 100), 2)
    change = round(price - base, 2)
    return price, change, round(change_pct, 2)

def gen_kline(code, base_price, days=30):
    """生成近30日K线数据"""
    klines = []
    price = base_price * random.uniform(0.85, 1.15)
    today = datetime.now()
    for i in range(days, 0, -1):
        date = (today - timedelta(days=i)).strftime("%Y-%m-%d")
        open_p = round(price * random.uniform(0.97, 1.03), 2)
        close_p = round(open_p * random.uniform(0.94, 1.06), 2)
        high_p = round(max(open_p, close_p) * random.uniform(1.0, 1.04), 2)
        low_p = round(min(open_p, close_p) * random.uniform(0.96, 1.0), 2)
        volume = int(random.uniform(10000, 500000))
        amount = round(volume * random.uniform(8, 25), 2)
        klines.append({
            "code": code,
            "trade_date": date,
            "open": open_p,
            "close": close_p,
            "high": high_p,
            "low": low_p,
            "volume": volume,
            "amount": amount
        })
        price = close_p
    return klines

